/// Bitmask per glyph: bit `row * GLYPH_W + col` is set where there is ink.
fn table() -> &'static HashMap<char, u64> {
    static TABLE: OnceLock<HashMap<char, u64>> = OnceLock::new();
    TABLE.get_or_init(|| {
        GLYPHS
            .iter()
            .map(|(ch, rows)| {
                let mut bits = 0u64;
                for (r, row) in rows.iter().enumerate() {
                    for (c, px) in row.chars().enumerate() {
                        if px == '#' {
                            bits |= 1 << (r * GLYPH_W as usize + c);
                        }
                    }
                }
                (*ch, bits)
            })
            .collect()
    })
}

/// Is there ink at (`col`, `row`) of this character?
///
/// Unknown characters fall back to `#`, so a missing glyph shows up as visible
/// junk rather than as a silent gap.
pub fn pixel(ch: char, col: u32, row: u32) -> bool {
    if col >= GLYPH_W || row >= GLYPH_H {
        return false;
    }
    let up = ch.to_ascii_uppercase();
    let t = table();
    let bits = t.get(&up).or_else(|| t.get(&'#')).copied().unwrap_or(0);
    bits & (1 << (row * GLYPH_W + col)) != 0
}

/// Width in pixels of `text` drawn at the given scale.
pub fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        (n * GLYPH_W + (n - 1) * TRACKING) * scale
    }
}

pub fn text_height(scale: u32) -> u32 {
    GLYPH_H * scale
}
