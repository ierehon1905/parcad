//! A 5x7 bitmap font, written as pictures so it can be checked by looking at it.
//!
//! Labels are not decoration here. A render an agent cannot name is a render it
//! cannot act on: "the hole on the left" is useless, "the hole in the TOP view"
//! is a fact. The same font draws the view labels and, later, the entity markers
//! that tie pixels back to tags.

