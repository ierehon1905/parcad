let targetPreviewRequest = 0;
/** A clicked treatment keeps its authored chain visible after pointer-leave. */
let pinnedTreatment: dsl.TreatmentSource | undefined;

/** A viewport hover marks source without moving the editor cursor or scroll. */
const setTreatmentHover = StateEffect.define<{ from: number; to: number } | undefined>();
const treatmentHover = StateField.define<DecorationSet>({
  create: () => Decoration.none,
  update(decorations, transaction) {
    for (const effect of transaction.effects) {
      if (effect.is(setTreatmentHover)) {
        return effect.value
          ? Decoration.set([Decoration.mark({ class: "cm-treatment-hover" }).range(effect.value.from, effect.value.to)])
          : Decoration.none;
      }
    }
    return decorations.map(transaction.changes);
  },
  provide: (field) => EditorView.decorations.from(field),
});

// ---------------------------------------------------------------- the editor

const editor = new EditorView({
  doc: BRACKET,
  parent: $("editor"),
  extensions: [
    basicSetup,
    javascript(),
    oneDark,
    treatmentHover,
    EditorView.updateListener.of((v) => {
      if (v.docChanged) {
        clearTargetPreview();
        pinnedTreatment = undefined;
        schedule();
      }
      if (v.selectionSet) previewTreatmentAtCursor();
    }),
  ],
});

// ------------------------------------------------------------ the eval cycle

let timer: number | undefined;
let running = false;
let dirty = false;

/**
 * Re-evaluate shortly after typing stops.
 *
 * Short enough to feel live, long enough that a burst of keystrokes is one
 * evaluation rather than twenty.
 */
function schedule() {
  window.clearTimeout(timer);
  timer = window.setTimeout(run, 350);
}

async function run() {
  if (running) {
    // Coalesce: remember that something changed and pick it up on the way out.
    dirty = true;
    return;
  }
  running = true;
  dirty = false;

  setStatus("evaluating", "busy");

  try {
    const built = buildGraph(editor.state.doc.toString());

    const depth = Number(depthInput.value);
    const result = await evaluateGraph(built.graph, depth, backendSelect.value);

    // The browser fallback is a fixed geometry artifact. Reflect its real
    // backend in the disabled selector instead of leaving it claiming that a
    // coarse SDF mesh is a B-rep solid.
    if (!inTauri) {
      backendSelect.value = result.backend === "brep" ? "brep" : "preview";
      syncBackendUi();
    }

    lastGraph = built.graph;
    lastSource = built.source;
    lastTreatments = built.treatments;
    show(result);
    previewTreatmentAtCursor();
    clearError();
    const ms =
      result.backend === "brep"
        ? result.timings.kernel_ms
        : result.timings.lower_and_mesh_ms + result.timings.normals_ms;
    setStatus(`${result.report.mesh.triangles.toLocaleString()} tris · ${ms} ms`);
  } catch (e) {
    showError(e);
    setStatus("failed", "failed");
  } finally {
    running = false;
    if (dirty) schedule();
  }
}

/** Is the Tauri bridge present, or are we in a plain browser? */
const inTauri = "__TAURI_INTERNALS__" in window || "__TAURI__" in window;

/**
 * Evaluate a graph, or serve a pre-baked one when there is no desktop shell.
 *
 * The fallback exists so the viewport can be developed and looked at in a normal
 * browser, where the geometry backend does not exist. It rebuilds the intent
 * graph only to preserve source locations; its geometry remains a fixed bracket
 * fixture, which the status line makes explicit.
 */
async function evaluateGraph(
  graph: unknown,
  depth: number,
  backend: string,
): Promise<Evaluated> {
  if (inTauri) return invoke<Evaluated>("evaluate", { graph, depth, backend });

  const res = await fetch("/dev-geometry.json");
  if (!res.ok) {
    throw new Error(
      "no desktop backend, and no /dev-geometry.json to fall back on.\n" +
        "Generate one with:\n" +
        "  parcad graph.json --geometry app/public/dev-geometry.json",
    );
  }
  return res.json() as Promise<Evaluated>;
}

/**
 * In a plain browser there is no geometry backend, so the viewport shows a
 * pre-baked file and the backend and detail controls do nothing. The untouched
 * bracket source can still demonstrate its baked treatment-history link; any
 * edited model needs the desktop app for live geometry and exact target preview.
 */
function markBrowserOnly() {
  if (inTauri) return;
  for (const el of [backendSelect, depthInput]) {
    el.disabled = true;
    el.title = "needs the desktop app — the browser shows pre-baked geometry";
  }
  const note = document.createElement("div");
  note.className = "notice";
  note.textContent =
    "Browser fixture: frozen bracket geometry from /dev-geometry.json. " +
    "Hover a corner marker to inspect its vertex ID and selector. " +
    "Edits and source-to-viewport target previews need the desktop app.";
  $("viewport-pane").appendChild(note);
}

/**
 * Run a script and flatten what it returns.
 *
 * The DSL is injected as named parameters rather than as globals, so a script
 * cannot accidentally depend on anything the page happens to have lying around.
 */
function buildGraph(source: string): BuiltGraph {
  const api = { ...dsl } as Record<string, unknown>;
  const names = Object.keys(api);

  let fn: (...args: unknown[]) => unknown;
  try {
    const executable = instrumentTreatmentCalls(editor.state, source);
    fn = new Function(...names, `${executable}\n//# sourceURL=parcad-editor.js`) as (...args: unknown[]) => unknown;
  } catch (e) {
    throw new Error(`the script did not parse:\n${(e as Error).message}`);
  }

  const result = fn(...names.map((n) => api[n]));
  if (!(result instanceof Shape)) {
    throw new Error(
      "the script must return a shape.\n" +
        "End it with something like:  return body.cut(hole)",
    );
  }
  const treatments: dsl.TreatmentSource[] = [];
  return { graph: dsl.build(result, treatments), source, treatments };
}

function show(result: Evaluated) {
  const { report } = result;
  visibleEdges = normalizeEdges(result.edges);
  visibleVertices = verticesFromEdges(visibleEdges);

  viewport.setGeometry(
    {
      positions: new Float32Array(result.positions),
      normals: new Float32Array(result.normals),
      indices: new Uint32Array(result.indices),
      edges: visibleEdges,
    },
    report.bounds,
  );

  // Frame once, then leave the camera alone — nothing is more irritating than a
  // view that resets itself every time you change a number.
  if (!framed) {
    viewport.frameAll(report.bounds);
    framed = true;
  }

  const { size, mass, mesh } = report;
  const dead = report.total_nodes - report.live_nodes;
  const linkedEdges = visibleEdges.filter((edge) => treatmentForEdge(edge)).length;
  const linkedMethods = [...new Set(
    visibleEdges
      .map(treatmentForEdge)
      .filter((treatment): treatment is dsl.TreatmentSource => !!treatment)
      .map((treatment) => `.${treatment.source?.method ?? treatment.kind}`),
  )];
  // "resolution" means different things per backend and the difference matters:
  // a grid spacing is where samples were taken, a deflection is a bound on how
  // far the result can be from the truth. Label them apart.
  const tol =
    result.backend === "brep"
      ? `within <b>${mesh.resolution_mm.toFixed(3)}</b> mm of the true surface`
      : `at <b>${mesh.resolution_mm.toFixed(3)}</b> mm grid`;

  reportEl.innerHTML = [
    `<b>${fmt(size.x)} × ${fmt(size.y)} × ${fmt(size.z)}</b> mm`,
    `volume <b>${fmt(mass.volume_mm3)}</b> mm³ · area <b>${fmt(mass.area_mm2)}</b> mm²`,
    result.topology
      ? `topology <b>${result.topology.faces}</b> faces · <b>${result.topology.edges}</b> edges`
      : "",
    `mesh <b>${mesh.triangles.toLocaleString()}</b> tris ${tol} ` +
      (mesh.watertight
        ? `<span class="ok">watertight</span>`
        : `<span class="warn">NOT watertight — ${mesh.non_manifold_edges} bad edges</span>`),
    report.tags.length ? `tags ${report.tags.join(", ")}` : "no tags",
    linkedEdges
      ? `<span class="ok">source links <b>${linkedEdges}</b> final curves → ${linkedMethods.join(", ")}</span>`
      : lastTreatments.length
        ? "<span class=\"warn\">source links: no final treatment curves are available</span>"
        : "source links — no edge treatments",
    dead > 0 ? `<span class="warn">${dead} unused nodes</span>` : "",
  ]
    .filter(Boolean)
    .join("<br>");
}

/**
 * Keep the browser-only development artifact usable until it is regenerated.
 * The desktop worker always returns the metadata-rich form; older artifacts
 * contain bare polylines and can still be hovered, just without a direction.
 */
function normalizeEdges(edges: EdgeCurve[]): EdgeCurve[] {
  if (!Array.isArray(edges) || edges.length === 0 || !Array.isArray(edges[0])) return edges;

  return (edges as unknown as number[][][]).map((points, index) => {
    const center: [number, number, number] = [0, 0, 0];
    let length = 0;
    for (let i = 0; i < points.length; i++) {
      for (let axis = 0; axis < 3; axis++) center[axis] += points[i][axis];
      if (i > 0) length += Math.hypot(
        points[i][0] - points[i - 1][0],
        points[i][1] - points[i - 1][1],
        points[i][2] - points[i - 1][2],
      );
    }
    for (let axis = 0; axis < 3; axis++) center[axis] /= points.length;
    return { id: `edge@${index}`, points, center, direction: null, length_mm: length };
  });
}

/** Clear an in-flight or displayed source-to-viewport target preview. */
function clearTargetPreview() {
  targetPreviewRequest++;
  viewport.setTargetPreview([]);
  targetPreviewEl.hidden = true;
}

/** Resolve and highlight the treatment call under the editor cursor. */
async function previewTreatmentAtCursor() {
  const request = ++targetPreviewRequest;
  const source = editor.state.doc.toString();
  const treatment =
    source === lastSource ? treatmentAtCursor(source, editor.state.selection.main.head) : undefined;
  if (!treatment || !lastGraph || !inTauri) {
    if (request === targetPreviewRequest) clearTargetPreview();
    return;
  }

  viewport.setTargetPreview([]);
  targetPreviewEl.hidden = false;
  targetPreviewName.textContent = `.${treatment.source!.method} input edges`;
  targetPreviewDetail.textContent = "resolving exact target…";

  try {
    const preview = await invoke<TargetPreview>("inspect_edge_target", {
      graph: lastGraph,
      node: treatment.node,
    });
    if (request !== targetPreviewRequest) return;
    if (preview.node !== treatment.node) throw new Error("the worker returned a different treatment");
    viewport.setTargetPreview(normalizeEdges(preview.edges));
    targetPreviewDetail.textContent = `${preview.edges.length} selected edge${preview.edges.length === 1 ? "" : "s"}`;
  } catch {
    if (request !== targetPreviewRequest) return;
    clearTargetPreview();
  }
}

/** Find a treatment method name at the current cursor, never by node ordering. */
function treatmentAtCursor(source: string, cursor: number): dsl.TreatmentSource | undefined {
  return lastTreatments.find((treatment) => {
    if (!treatment.source || treatment.source.line < 1 || treatment.source.column < 1) return false;
    const start = sourceOffset(source, treatment.source.line, treatment.source.column);
    return start !== undefined && cursor >= start && cursor <= start + treatment.source.method.length;
  });
}

/** Show the hovered B-rep entity's temporary ID and a semantic selector. */
function updateEntityInspector() {
  const vertex = hoveredVertex ?? selectedVertex;
  if (vertex) {
    edgeInspector.hidden = false;
    entityInspectorTitle.textContent = "vertex inspector";
    edgeIdEl.textContent = vertex.id;
    edgeDetailEl.textContent = `(${vertex.point.map(fmt).join(", ")}) mm · ${vertex.degree} incident edge${vertex.degree === 1 ? "" : "s"}`;
    edgeOriginEl.hidden = true;
    suggestedSelector = suggestVertexSelector(vertex, visibleVertices);
    edgeSelectorEl.textContent = suggestedSelector
      ? `vertices: ${suggestedSelector}`
      : "no unique directional vertex selector";
    copyEdgeSelector.textContent = "copy vertex selector";
    copyEdgeSelector.disabled = !suggestedSelector;
    copyEdgeSelector.title = suggestedSelector
      ? "Copy a selector for shape.vertices(…); it is re-resolved on each evaluation"
      : "Add a stronger directional condition after changing the model";
    return;
  }

  const edge = hoveredEdge ?? selectedEdge;
  if (!edge) {
    edgeInspector.hidden = true;
    edgeOriginEl.hidden = true;
    suggestedSelector = undefined;
    return;
  }

  edgeInspector.hidden = false;
  entityInspectorTitle.textContent = "edge inspector";
  edgeIdEl.textContent = edge.id;
  const direction = edge.direction ? ` · ${directionLabel(edge.direction)}` : "";
  edgeDetailEl.textContent = `${fmt(edge.length_mm)} mm${direction}`;
  const treatment = treatmentForEdge(edge);
  edgeOriginEl.hidden = !treatment;
  if (treatment) {
    const method = treatment.source?.method ?? treatment.kind;
    edgeOriginEl.textContent = `from .${method}(…) · click to lock code`;
  }
  suggestedSelector = suggestEdgeSelector(edge, visibleEdges);
  edgeSelectorEl.textContent = suggestedSelector
    ? `selector: ${suggestedSelector}`
    : "no unique directional selector";
  copyEdgeSelector.textContent = "copy selector";
  copyEdgeSelector.disabled = !suggestedSelector;
  copyEdgeSelector.title = suggestedSelector
    ? "Copy a selector for shape.edges(…); it is re-resolved on each evaluation"
    : "Add a stronger directional condition, or use a future point/adjacency selector";
}

/** The source call whose exact builder history generated this final edge. */
function treatmentForEdge(edge: EdgeCurve): dsl.TreatmentSource | undefined {
  // The browser artifact is generated from exactly BRACKET. Let it demonstrate
  // the link, but never pretend an edited source still owns its frozen curves.
  if (!inTauri && lastSource !== BRACKET) return undefined;
  return edge.treatment_node === undefined
    ? undefined
    : lastTreatments.find((treatment) => treatment.node === edge.treatment_node);
}

/** Mark the source call for a final edge without stealing keyboard focus. */
function highlightTreatmentForEdge(edge: EdgeCurve | undefined) {
  const treatment = edge && editor.state.doc.toString() === lastSource
    ? treatmentForEdge(edge)
    : undefined;
  if (!treatment && pinnedTreatment) return;
  const range = treatmentRange(treatment);
  editor.dispatch({ effects: setTreatmentHover.of(range) });
  if (range && !rangeIsVisible(range)) {
    editor.dispatch({ effects: EditorView.scrollIntoView(range.from, { y: "center" }) });
  }
}

function rangeIsVisible(range: { from: number; to: number }): boolean {
  const start = editor.coordsAtPos(range.from);
  const end = editor.coordsAtPos(range.to);
  const pane = editor.scrollDOM.getBoundingClientRect();
  return !!start && !!end && start.top >= pane.top && end.bottom <= pane.bottom;
}

/** Select and reveal a treatment call after its generated edge is clicked. */
function focusTreatmentForEdge(edge: EdgeCurve | undefined) {
  if (!edge || editor.state.doc.toString() !== lastSource) {
    clearPinnedTreatment();
    return;
  }
  const treatment = treatmentForEdge(edge);
  const range = treatmentRange(treatment);
  if (!treatment?.source || !range) {
    clearPinnedTreatment();
    return;
  }

  const start = sourceOffset(lastSource, treatment.source.line, treatment.source.column);
  if (start === undefined) return;
  pinnedTreatment = treatment;
  editor.dispatch({
    selection: { anchor: start, head: start + treatment.source.method.length },
    effects: [
      setTreatmentHover.of(range),
      EditorView.scrollIntoView(start, { y: "center" }),
    ],
  });
}

function treatmentRange(treatment: dsl.TreatmentSource | undefined) {
  return treatment?.source
    ? treatmentCallRange(editor.state, lastSource, treatment.source)
    : undefined;
}

function clearPinnedTreatment() {
  pinnedTreatment = undefined;
  editor.dispatch({ effects: setTreatmentHover.of(undefined) });
}

function directionLabel(direction: [number, number, number]): string {
  const components = direction.map(Math.abs);
  const index = components.indexOf(Math.max(...components));
  return `|${["X", "Y", "Z"][index]}`;
}

/**
 * Derive the shortest `>X`, `<Y`, `|Z` conjunction that identifies this
 * currently visible edge. It is a convenience for the inspector, not a hidden
 * ID: if the geometry later becomes ambiguous, the B-rep evaluator refuses.
 */
function suggestEdgeSelector(edge: EdgeCurve, all: EdgeCurve[]): string | undefined {
  if (all.length === 0) return undefined;
  const axes = ["X", "Y", "Z"] as const;
  const terms: string[] = [];
  const epsilon = 1e-4;

  if (edge.direction) {
    const axis = edge.direction.map(Math.abs).indexOf(Math.max(...edge.direction.map(Math.abs)));
    if (Math.abs(edge.direction[axis]) >= 0.999) terms.push(`|${axes[axis]}`);
  }
  for (let axis = 0; axis < 3; axis++) {
    const values = all.map((candidate) => candidate.center[axis]);
    const maximum = Math.max(...values);
    const minimum = Math.min(...values);
    if (Math.abs(edge.center[axis] - maximum) <= epsilon) terms.push(`>${axes[axis]}`);
    if (Math.abs(edge.center[axis] - minimum) <= epsilon) terms.push(`<${axes[axis]}`);
  }

  const matches = (candidate: EdgeCurve, term: string) => {
    const axis = axes.indexOf(term[1] as (typeof axes)[number]);
    if (term[0] === "|") {
      return candidate.direction !== null && Math.abs(candidate.direction[axis]) >= 0.999;
    }
    const values = all.map((other) => other.center[axis]);
    const extreme = term[0] === ">" ? Math.max(...values) : Math.min(...values);
    return Math.abs(candidate.center[axis] - extreme) <= epsilon;
  };

  const selected: string[] = [];
  let candidates = all;
  while (candidates.length > 1) {
    const currentCount = candidates.length;
    const next = terms
      .filter((term) => !selected.includes(term))
      .map((term) => ({ term, candidates: candidates.filter((candidate) => matches(candidate, term)) }))
      .filter(({ candidates: remaining }) => remaining.length > 0 && remaining.length < currentCount)
      .sort((a, b) => a.candidates.length - b.candidates.length)[0];
    if (!next || next.candidates.length >= candidates.length) break;
    selected.push(next.term);
    candidates = next.candidates;
  }

  return candidates.length === 1 && selected.length > 0 ? selected.join(" and ") : undefined;
}

copyEdgeSelector.addEventListener("click", async () => {
  if (!suggestedSelector || !navigator.clipboard) return;
  try {
    await navigator.clipboard.writeText(suggestedSelector);
    setStatus(`copied ${suggestedSelector}`);
  } catch {
    setStatus("could not copy selector", "failed");
  }
});

const fmt = (v: number) =>
  Math.abs(v) >= 1000 ? v.toFixed(0) : v.toFixed(2).replace(/\.00$/, "");

function setStatus(text: string, cls = "") {
  statusEl.textContent = text;
  statusEl.className = `status ${cls}`;
}

function showError(e: unknown) {
  errorEl.textContent = e instanceof Error ? e.message : String(e);
  errorEl.hidden = false;
  // Leave the last good geometry on screen. A broken edit mid-typing should not
  // blank the viewport.
}

function clearError() {
  errorEl.hidden = true;
  errorEl.textContent = "";
}

