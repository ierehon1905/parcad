interface Report {
  units: string;
  bounds: { min: Vec3; max: Vec3 };
  size: Vec3;
  framing_bounds: { min: Vec3; max: Vec3 };
  mass: { volume_mm3: number; area_mm2: number; centroid: Vec3 };
  mesh: {
    vertices: number;
    triangles: number;
    resolution_mm: number;
    watertight: boolean;
    non_manifold_edges: number;
  };
  tags: string[];
  live_nodes: number;
  total_nodes: number;
}

interface Vec3 {
  x: number;
  y: number;
  z: number;
}

interface Evaluated {
  positions: number[];
  normals: number[];
  indices: number[];
  /** Logical edge curves. Omitted in mesh-preview mode. */
  edges: EdgeCurve[];
  /** Face and edge counts. Null in mesh-preview mode, where the question does
   *  not apply — which is different from the answer being zero. */
  topology: { faces: number; edges: number } | null;
  backend: "implicit" | "brep";
  report: Report;
  timings: {
    lower_and_mesh_ms: number;
    normals_ms: number;
    kernel_ms: number;
  };
}

interface BuiltGraph {
  graph: dsl.Doc;
  source: string;
  treatments: dsl.TreatmentSource[];
}

interface TargetPreview {
  node: number;
  edges: EdgeCurve[];
}

/** A visible B-rep edge. `id` is valid only for this evaluated result. */
interface EdgeCurve {
  id: string;
  points: number[][];
  center: [number, number, number];
  direction: [number, number, number] | null;
  length_mm: number;
  /** Ephemeral source node when this final edge was generated by a treatment. */
  treatment_node?: number;
}

